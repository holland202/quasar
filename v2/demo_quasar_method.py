"""
QUASAR METHOD DEMO — runs anywhere NumPy runs, including a phone.
====================================================================
This is not a highlight reel. It reproduces, live, a claim I made,
the two defects that voided it, and the corrected result.

    pip install numpy && python3 demo_quasar_method.py

Task: single-qubit trajectories on the Bloch ball. Each trajectory is
generated by ONE unknown linear map (rotation + decay). A predictor
must guess the next state. Candidate "local maps" are ridge-fit from
chunks of past transitions; attention weights them; we ask whether
weighting beats a blind uniform average.

Registered up front, before any number is printed:
  P0  ANTI-VACUITY: attention must beat the blind average by >=5%.
      Below that, no claim in either direction.
  P1  With temperature matched and leakage removed, the gap between
      Bures-metric scoring and plain dot-product scoring should
      COLLAPSE below 3% relative. If it survives, geometry is real.
"""
import sys, time
import numpy as np

# ------------------------------------------------------------------
def so3(axis, w):
    a = axis / (np.linalg.norm(axis) + 1e-12)
    K = np.array([[0,-a[2],a[1]],[a[2],0,-a[0]],[-a[1],a[0],0]])
    return np.eye(3) + np.sin(w)*K + (1-np.cos(w))*(K @ K)

def project_bloch(r):
    n = np.linalg.norm(r, axis=-1, keepdims=True)
    return np.where(n > 1, r/np.maximum(n,1e-12), r)

def bures(r1, r2):
    d = np.sum(r1*r2, axis=-1)
    m1 = np.linalg.norm(r1,axis=-1); m2 = np.linalg.norm(r2,axis=-1)
    F = 0.5*(1 + d + np.sqrt(np.maximum(0,(1-m1**2)*(1-m2**2))))
    return np.arccos(np.sqrt(np.clip(F,0,1)))

def softmax(x):
    e = np.exp(x-np.max(x)); return e/e.sum()

def ent(p):
    p = np.clip(p,1e-12,1); return float(-np.sum(p*np.log(p)))

def ridge(X, Y, lam=0.3):
    return Y.T @ X @ np.linalg.inv(X.T @ X + lam*np.eye(3))

def traj(rng, axis, w, g, n):
    r = rng.standard_normal(3); r /= np.linalg.norm(r)
    R = so3(axis,w); dec = np.exp(-g)
    T = np.zeros((n+1,3)); T[0] = r
    for t in range(n):
        r = dec*(R@r); T[t+1] = project_bloch(r)
    return T

def channels(regime, K=6):
    rng = np.random.default_rng(999); out=[]
    if regime=="direction":
        for _ in range(K):
            a = rng.standard_normal(3); a/=np.linalg.norm(a)
            out.append((a, rng.uniform(0.5,1.2), 0.05))
    else:
        for g in np.linspace(0.02,0.30,K):
            out.append((np.array([0.,0.,1.]), 0.8, g))
    return out

def score(M, xp, xn, arm):
    p = project_bloch(M @ xp)
    return -float(bures(p,xn)**2) if arm=="geo" else -float(np.sum((p-xn)**2))

def hdr(n, title):
    print(f"\n{'='*68}\n  STAGE {n} — {title}\n{'='*68}")

t0 = time.time()
print("="*68)
print("  QUASAR METHOD DEMO")
print("  a claim, the defects that voided it, the corrected number")
print("="*68)
print("\nRegistered before running:")
print("  P0  attention must beat blind average by >=5% or no claim")
print("  P1  geo-vs-dot gap should collapse below 3% once temperature")
print("      is matched and leakage removed")

