hdr(1, "THE LEAK (found in code already sent out as a result)")
print("""
Candidates are ridge-fit from disjoint chunks of past transitions.
The original loop ran `while lo+CHUNK <= t`. Trace what that includes
at each query point t, with CHUNK=2, and compare against the one
transition used to SCORE candidate quality: (t-1)->(t).
""")
CH=2; leaks=0; tot=0
for t in range(2*CH, 9):
    ch=[]; lo=0
    while lo+CH<=t:
        ch.append((lo,[(i,i+1) for i in range(lo,lo+CH)])); lo+=CH
    scored=(t-1,t); bad=[l for l,tr_ in ch if scored in tr_]
    tot+=1; leaks+= 1 if bad else 0
    tag = f"LEAKED (chunk lo={bad[0]})" if bad else "clean"
    print(f"   t={t}:  scored transition {scored}  ->  {tag}")
print(f"\n   {leaks} of {tot} query points scored on data the candidate")
