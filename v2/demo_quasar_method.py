hdr(4, "VERDICT")
for regime,(G,D,B) in results.items():
    marg=(B.mean()-min(G.mean(),D.mean()))/B.mean()
    gap=abs(G.mean()-D.mean())/min(G.mean(),D.mean())
    print(f"\n   [{regime} regime]")
    print(f"     blind (uniform avg) : {B.mean():.6f} +- {B.std():.6f}")
    print(f"     geo   (Bures score) : {G.mean():.6f} +- {G.std():.6f}")
    print(f"     dot   (dot score)   : {D.mean():.6f} +- {D.std():.6f}")
    print(f"     P0 attention beats blind by >=5% : {marg>=0.05}  ({100*marg:+.1f}%)")
    print(f"     P1 geo-vs-dot gap collapses <3%  : {gap<0.03}  ({100*gap:.2f}%)")

