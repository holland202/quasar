hdr(3, "THE FIX — leak-free chunks, matched temperature")
CHUNK, SEQ, TGT = 4, 20, 0.60
def cands(T, t):
    M=[]; lo=0
    while lo+CHUNK <= t-1:
        M.append(ridge(T[lo:lo+CHUNK], T[lo+1:lo+CHUNK+1])); lo+=CHUNK
    return M

def gather(regime, seed, n):
    ch = channels(regime); rng = np.random.default_rng(seed); out=[]
    for _ in range(n):
        k = rng.integers(0,len(ch)); T = traj(rng,*ch[k],SEQ)
        for t in range(2*CHUNK+1, SEQ):
            c = cands(T,t)
            if len(c)>=2: out.append((c,T[t-1],T[t],T[t+1]))
    return out

def meanH(beta, arm, data):
    v=[]
    for c,xp,xn,_ in data:
        r=np.array([score(M,xp,xn,arm) for M in c])
        v.append(ent(softmax(beta*r))/np.log(len(c)))
    return float(np.mean(v))

def calibrate(arm, data):
    lo,hi=1e-3,1e5
    for _ in range(40):
        mid=np.sqrt(lo*hi)
        if meanH(mid,arm,data)>TGT: lo=mid
        else: hi=mid
    b=np.sqrt(lo*hi); return b, meanH(b,arm,data)

print("\n   Calibrating BETA per arm so both sit at identical sharpness...")
results={}
for regime in ("direction","purity"):
    cal = gather(regime, 7777, 15)
    bg,hg = calibrate("geo",cal); bd,hd = calibrate("dot",cal)
    print(f"\n   [{regime}]  BETA_geo={bg:>10.3f} (H={hg:.4f})   "
          f"BETA_dot={bd:>9.3f} (H={hd:.4f})")
    print(f"              calibrated betas differ {max(bg,bd)/min(bg,bd):.1f}x "
          f"-> they were NEVER matched at 6.0")
    G,D,B=[],[],[]
    for s in range(4):
        data = gather(regime, 1000+s, 25)
        g,d,b=[],[],[]
        for c,xp,xn,nx in data:
            Ms=np.stack(c)
            rg=np.array([score(M,xp,xn,"geo") for M in c])
            rd=np.array([score(M,xp,xn,"dot") for M in c])
            for arr,M in ((g,np.tensordot(softmax(bg*rg),Ms,axes=(0,0))),
                          (d,np.tensordot(softmax(bd*rd),Ms,axes=(0,0))),
                          (b,Ms.mean(axis=0))):
                arr.append(bures(project_bloch(M@xn),nx)**2)
        G.append(np.mean(g)); D.append(np.mean(d)); B.append(np.mean(b))
    results[regime]=(np.array(G),np.array(D),np.array(B))
    sys.stdout.write("              running seeds... done\n")

